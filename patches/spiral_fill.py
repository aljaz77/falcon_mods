"""Spiral fill: a "Spiral" tool next to Offset that turns the selected closed shapes into one
continuous spiral line on a Line Engraving layer.

The toolpath is generated by FalconModsSpiral.js inside a hidden WebEngineView (see
qml/FalconModsSpiralButton.qml). Both scripts are embedded here as one string, because the page
can't load qrc resources and QML's JS engine is too slow to run the generator itself.
"""
import json
import os

ID = "spiral_fill"
DESCRIPTION = "Spiral fill tool: one continuous spiral toolpath instead of separate rings"

_HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "qml")


def _page_code():
    parts = []
    for name in ("FalconModsSpiral.js", "FalconModsSpiralPage.js"):
        with open(os.path.join(_HERE, name), encoding="utf-8") as f:
            parts.append(f.read().replace(".pragma library\n", "", 1))
    code = "\n".join(parts)
    # QML module wrapper; json.dumps gives a valid JS string literal
    return ".pragma library\n// generated by patches/spiral_fill.py\nvar code = " + json.dumps(code) + "\n"


TOOLBAR = "ClTopToolBar.qml"

PATCHES = [
    {"rcc": "qml.rcc", "file": "FalconModsSpiralButton.qml", "new_file": True,
     "source": "qml/FalconModsSpiralButton.qml"},
    {"rcc": "qml.rcc", "file": "FalconModsSpiralSource.js", "new_file": True, "content": _page_code()},
    {"rcc": "qml.rcc", "file": "image/falconmods/spiral.svg", "new_file": True, "source": "qml/spiral.svg"},
    {
        "rcc": "qml.rcc",
        "file": TOOLBAR,
        "find": "        // 偏移效果\n        ClToolButtonIUT {\n            action: actionOffset\n",
        "replace": (
            "        // FalconMods: spiral fill\n"
            "        FalconModsSpiralButton {\n"
            "            canvas: clCanvas\n"
            "            hoveredColor: hoveredBackgroundColor\n"
            "            palette.buttonText: enabled ? normalBackgroundColor : greyOutBackgroundColor\n"
            "        }\n\n"
            "        // 偏移效果\n        ClToolButtonIUT {\n            action: actionOffset\n"
        ),
    },
]
